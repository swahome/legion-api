-- ---- Investments ----

CREATE TABLE asset_categories (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id   integer UNIQUE,
    group_id    bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    name        text NOT NULL,
    slug        text NOT NULL DEFAULT '',
    description text NOT NULL DEFAULT '',
    is_hidden   boolean NOT NULL DEFAULT false,
    is_active   boolean NOT NULL DEFAULT true,
    created_by  bigint REFERENCES users (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (group_id, id)
);

-- What the group owns. Purchase payments are asset_purchase withdrawals and
-- sales are asset_sale deposits, both linked by asset_id.
CREATE TABLE assets (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id         integer UNIQUE,
    group_id          bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    asset_category_id bigint,
    name              text NOT NULL,
    cost              numeric(14, 2) NOT NULL DEFAULT 0,
    description       text NOT NULL DEFAULT '',
    is_backdated      boolean NOT NULL DEFAULT false,
    created_by        bigint REFERENCES users (id),
    created_at        timestamptz NOT NULL DEFAULT now(),
    voided_at         timestamptz,
    UNIQUE (group_id, id),
    FOREIGN KEY (group_id, asset_category_id) REFERENCES asset_categories (group_id, id)
);

-- Shares the group bought. The purchase is a stock_purchase withdrawal; each
-- sale is a stock_sales row with its stock_sale deposit.
CREATE TABLE stocks (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id       integer UNIQUE,
    group_id        bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    name            text NOT NULL,
    purchase_date   date NOT NULL,
    shares          numeric(16, 4) NOT NULL CHECK (shares > 0),
    shares_sold     numeric(16, 4) NOT NULL DEFAULT 0,
    purchase_price  numeric(14, 4) NOT NULL,
    current_price   numeric(14, 4) NOT NULL,
    account_id      bigint,
    is_backdated    boolean NOT NULL DEFAULT false,
    created_by      bigint REFERENCES users (id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    voided_at       timestamptz,
    UNIQUE (group_id, id),
    FOREIGN KEY (group_id, account_id) REFERENCES group_accounts (group_id, id)
);

CREATE TABLE stock_sales (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id      integer UNIQUE,
    group_id       bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    stock_id       bigint NOT NULL,
    account_id     bigint,
    sale_date      date NOT NULL,
    shares         numeric(16, 4) NOT NULL CHECK (shares > 0),
    price_per_share numeric(14, 4) NOT NULL,
    created_by     bigint REFERENCES users (id),
    created_at     timestamptz NOT NULL DEFAULT now(),
    voided_at      timestamptz,
    UNIQUE (group_id, id),
    FOREIGN KEY (group_id, stock_id) REFERENCES stocks (group_id, id),
    FOREIGN KEY (group_id, account_id) REFERENCES group_accounts (group_id, id)
);

-- Money placed with an institution. amount is what went in (the first
-- payment plus top ups, each a money_market_investment withdrawal); a cash
-- in is a money_market deposit and closes it.
CREATE TABLE money_market_investments (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id      integer UNIQUE,
    group_id       bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    institution    text NOT NULL,
    investment_date date NOT NULL,
    amount         numeric(14, 2) NOT NULL DEFAULT 0,
    description    text NOT NULL DEFAULT '',
    account_id     bigint,
    is_closed      boolean NOT NULL DEFAULT false,
    cash_in_amount numeric(14, 2),
    cash_in_date   date,
    is_backdated   boolean NOT NULL DEFAULT false,
    created_by     bigint REFERENCES users (id),
    created_at     timestamptz NOT NULL DEFAULT now(),
    voided_at      timestamptz,
    UNIQUE (group_id, id),
    FOREIGN KEY (group_id, account_id) REFERENCES group_accounts (group_id, id)
);

-- ---- Meetings ----

CREATE TABLE meetings (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id   integer UNIQUE,
    group_id    bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    title       text NOT NULL,
    venue       text NOT NULL DEFAULT '',
    purpose     text NOT NULL DEFAULT '',
    meeting_at  timestamptz NOT NULL,
    created_by  bigint REFERENCES users (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (group_id, id)
);
CREATE INDEX meetings_group_idx ON meetings (group_id, meeting_at DESC);

-- status: 1 present, 2 absent with apology, 3 late, 4 absent without apology.
CREATE TABLE meeting_attendance (
    meeting_id    bigint NOT NULL REFERENCES meetings (id) ON DELETE CASCADE,
    group_id      bigint NOT NULL,
    membership_id bigint NOT NULL,
    status        smallint NOT NULL CHECK (status BETWEEN 1 AND 4),
    PRIMARY KEY (meeting_id, membership_id),
    FOREIGN KEY (group_id, membership_id) REFERENCES memberships (group_id, id)
);

-- Agenda points and any other business, in the order given.
CREATE TABLE meeting_items (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    meeting_id bigint NOT NULL REFERENCES meetings (id) ON DELETE CASCADE,
    kind       text NOT NULL CHECK (kind IN ('agenda', 'aob')),
    name       text NOT NULL,
    position   integer NOT NULL DEFAULT 0
);
CREATE INDEX meeting_items_meeting_idx ON meeting_items (meeting_id, kind, position);

-- ---- Contribution transfers ----

-- Moving money a member has paid from one place to another: from a
-- contribution (or from a loan's repayments) to another contribution, a
-- fine, a loan, or the same three for another member. to_kind is where the
-- money lands; to_membership_id is the member it lands with.
CREATE TYPE transfer_kind AS ENUM ('contribution', 'fine', 'loan');

CREATE TABLE contribution_transfers (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id            integer UNIQUE,
    group_id             bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    membership_id        bigint NOT NULL,
    from_contribution_id bigint,
    from_loan_id         bigint,
    to_member            boolean NOT NULL DEFAULT false, -- legacy transfer_to 4 ("another member")
    to_kind              transfer_kind NOT NULL,
    to_membership_id     bigint NOT NULL,
    to_contribution_id   bigint,
    to_fine_category_id  bigint,
    to_loan_id           bigint,
    amount               numeric(14, 2) NOT NULL CHECK (amount > 0),
    transfer_date        date NOT NULL,
    description          text NOT NULL DEFAULT '',
    created_by           bigint REFERENCES users (id),
    created_at           timestamptz NOT NULL DEFAULT now(),
    voided_at            timestamptz,
    voided_by            bigint REFERENCES users (id),
    UNIQUE (group_id, id),
    CHECK ((from_contribution_id IS NULL) <> (from_loan_id IS NULL)),
    FOREIGN KEY (group_id, membership_id) REFERENCES memberships (group_id, id),
    FOREIGN KEY (group_id, to_membership_id) REFERENCES memberships (group_id, id),
    FOREIGN KEY (group_id, from_contribution_id) REFERENCES contributions (group_id, id),
    FOREIGN KEY (group_id, to_contribution_id) REFERENCES contributions (group_id, id),
    FOREIGN KEY (group_id, to_fine_category_id) REFERENCES fine_categories (group_id, id),
    FOREIGN KEY (group_id, from_loan_id) REFERENCES loans (group_id, id),
    FOREIGN KEY (group_id, to_loan_id) REFERENCES loans (group_id, id)
);
CREATE INDEX contribution_transfers_group_idx ON contribution_transfers (group_id, transfer_date DESC, id DESC);

ALTER TABLE ledger_entries ADD COLUMN contribution_transfer_id bigint REFERENCES contribution_transfers (id);
CREATE INDEX ledger_transfer_idx ON ledger_entries (contribution_transfer_id) WHERE contribution_transfer_id IS NOT NULL;
ALTER TABLE loan_charges ADD COLUMN contribution_transfer_id bigint REFERENCES contribution_transfers (id);
ALTER TABLE loan_repayments ADD COLUMN contribution_transfer_id bigint REFERENCES contribution_transfers (id);

