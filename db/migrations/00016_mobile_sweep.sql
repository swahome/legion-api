-- ---- Notifications ----

-- What a member sees in the app's notifications list. category keeps the
-- legacy numeric code; refs holds the legacy links (deposit_id, loan_id...).
CREATE TABLE notifications (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id         integer UNIQUE,
    group_id          bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    membership_id     bigint NOT NULL,
    user_id           bigint REFERENCES users (id) ON DELETE SET NULL,
    from_user_id      bigint REFERENCES users (id) ON DELETE SET NULL,
    subject           text NOT NULL DEFAULT '',
    message           text NOT NULL DEFAULT '',
    category          smallint NOT NULL DEFAULT 0,
    call_to_action    text NOT NULL DEFAULT '',
    link              text NOT NULL DEFAULT '',
    file_path         text NOT NULL DEFAULT '',
    file_type         text NOT NULL DEFAULT '',
    file_size         bigint,
    refs              jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_read           boolean NOT NULL DEFAULT false,
    created_at        timestamptz NOT NULL DEFAULT now(),
    read_at           timestamptz,
    FOREIGN KEY (group_id, membership_id) REFERENCES memberships (group_id, id) ON DELETE CASCADE
);
CREATE INDEX notifications_member_idx ON notifications (group_id, membership_id, created_at DESC, id DESC);
CREATE INDEX notifications_unread_idx ON notifications (group_id, membership_id) WHERE NOT is_read;

-- ---- Statement requests ----

-- The app asks for a statement by email or as a download; a background
-- job writes the PDF. kind: 1 contribution, 2 fine, 3 loan. action: 1 email,
-- 2 download (a notification carries the file).
CREATE TABLE statement_requests (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    group_id      bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    membership_id bigint NOT NULL,
    user_id       bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind          smallint NOT NULL CHECK (kind IN (1, 2, 3)),
    action        smallint NOT NULL CHECK (action IN (1, 2)),
    file_type     smallint NOT NULL DEFAULT 1,
    date_from     date NOT NULL,
    date_to       date NOT NULL,
    email         text NOT NULL DEFAULT '',
    loan_id       bigint,
    status        text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'done', 'failed')),
    attempts      integer NOT NULL DEFAULT 0,
    file_path     text NOT NULL DEFAULT '',
    error         text NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now(),
    done_at       timestamptz,
    FOREIGN KEY (group_id, membership_id) REFERENCES memberships (group_id, id) ON DELETE CASCADE
);
CREATE INDEX statement_requests_pending_idx ON statement_requests (created_at) WHERE status = 'pending';

-- ---- Subscription billing history (read only) ----

CREATE TABLE billing_packages (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id        integer UNIQUE,
    name             text NOT NULL,
    slug             text NOT NULL DEFAULT '',
    billing_type     smallint,
    monthly_amount   numeric(14, 2) NOT NULL DEFAULT 0,
    quarterly_amount numeric(14, 2) NOT NULL DEFAULT 0,
    annual_amount    numeric(14, 2) NOT NULL DEFAULT 0,
    percentage_tax   numeric(6, 2) NOT NULL DEFAULT 0,
    is_default       boolean NOT NULL DEFAULT false,
    is_active        boolean NOT NULL DEFAULT true,
    settings         jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE billing_invoices (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id       integer UNIQUE,
    group_id        bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    number          text NOT NULL DEFAULT '',
    billing_date    date,
    due_date        date,
    amount          numeric(14, 2) NOT NULL DEFAULT 0,
    tax             numeric(14, 2) NOT NULL DEFAULT 0,
    prorated_amount numeric(14, 2) NOT NULL DEFAULT 0,
    amount_paid     numeric(14, 2) NOT NULL DEFAULT 0,
    billing_cycle   smallint,
