    is_paid         boolean NOT NULL DEFAULT false,
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX billing_invoices_group_idx ON billing_invoices (group_id, due_date DESC);

CREATE TABLE billing_payments (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id        integer UNIQUE,
    group_id         bigint NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
    receipt_number   text NOT NULL DEFAULT '',
    receipt_date     date,
    amount           numeric(14, 2) NOT NULL DEFAULT 0,
    tax              numeric(14, 2) NOT NULL DEFAULT 0,
    payment_method   smallint,
    transaction_code text NOT NULL DEFAULT '',
    invoice_id       bigint REFERENCES billing_invoices (id),
    package_id       bigint REFERENCES billing_packages (id),
    description      text NOT NULL DEFAULT '',
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX billing_payments_group_idx ON billing_payments (group_id, receipt_date DESC);

